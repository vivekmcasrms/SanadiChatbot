export type TKey = keyof typeof en;
const dict: Record<Lang, Record<TKey, string>> = { en, ar };
/** Translate in an explicit language (e.g. the language of one chat message). */
export function translate(lang: Lang, key: TKey): string {
  return dict[lang][key] ?? dict.en[key] ?? key;
}

type Ctx = {
  lang: Lang;
  dir: "ltr" | "rtl";
  t: (key: TKey) => string;
  setLang: (lang: Lang) => void;
};

// Keep one context instance across hot reloads so a reloaded module never
// orphans providers rendered by the previous module instance.
const g = globalThis as unknown as { __sanadiI18nCtx?: React.Context<Ctx | null> };
const I18nContext = (g.__sanadiI18nCtx ??= createContext<Ctx | null>(null));
const STORAGE_KEY = "uaeu.lang";

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    if (stored === "ar" || stored === "en") setLangState(stored);
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  }, [lang]);

  const setLang = useCallback((next: Lang) => {
    setLangState(next);
    window.localStorage.setItem(STORAGE_KEY, next);
  }, []);

  const t = useCallback((key: TKey) => dict[lang][key] ?? dict.en[key] ?? key, [lang]);

  const value = useMemo<Ctx>(
    () => ({ lang, dir: lang === "ar" ? "rtl" : "ltr", t, setLang }),
    [lang, t, setLang],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside I18nProvider");
  return ctx;
}

/** Arabic flag for shared UI primitives that may render outside the provider. */
export function useIsArabic(): boolean {
  return useContext(I18nContext)?.lang === "ar";
}

/** Picks the right localized column from a bilingual row. */
export function pick<T extends Record<string, unknown>>(row: T, base: string, lang: Lang): string {
  const value = row[`${base}_${lang}`] ?? row[`${base}_en`];
  return typeof value === "string" ? value : "";
}